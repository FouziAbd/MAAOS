"""DK4 — `create-domain` and the real second-domain proof.

Part 1 (commit A — the scaffold):
  - `render()` produces the six files, each with the name substituted and no template marker
    left; a freshly generated domain validates with 0 FAIL / 0 WARN, its layout and lazy
    backend checks pass, its generated test passes, and both policies reach the goal — all
    in a throwaway copy, never in the working tree;
  - `create_domain` writes NEW files only: it refuses an existing directory, an existing test
    file, an invalid/reserved/registered name, and a target outside the repository, and it
    never touches `domains/registry.py` (the registry lines are printed);
  - the CLI subcommand: exit 0 with the next steps, exit 1 on a refusal.

Part 2 (commit B — the proof, `tests/fixture_lamp/`): the fixture was generated by the exact
command a user runs (`python -m maaos create-domain lamp --target tests/fixture_lamp`, commit
A is byte-identical to the generator's output) and then changed ONLY through the documented
extension points to a small deterministic domain with a designed physical failure:
  - the fixture's file set equals the scaffold's and every `# TODO(author)` extension point
    is still present (evidence that only extension points were edited);
  - the lamp domain validates with 0 FAIL / 0 WARN; the sticky lamp makes an applicable
    `TurnOn` fail physically; `symbolic_primary` halts on the repeated failure with the
    typed discrepancies, `advisory_two_track` recovers through the recovery advice
    (`Nudge`, then `TurnOn`) and reaches the goal;
  - AST import pins per role (the fixture's `types.py`/`model.py`/`environment.py` import
    only stdlib + shared + kit + siblings; `__init__.py` only app/kit/shared + siblings), the
    guard's own role scanner agrees on a copy placed under `domains/`, and a subprocess pin
    that a full episode loads no `domain`/`symbolic`/`nl`/`app.box_push_v1`/`app.comparator`/
    backend module.

Offline and deterministic.
"""
