def _scratch_repo(stack) -> pathlib.Path:
    """A throwaway copy of the packages a generated domain imports, so a scaffold can be
    generated, imported and validated without touching the working tree."""
    root = pathlib.Path(stack.enter_context(tempfile.TemporaryDirectory()))
    for package in ("shared", "runtime", "app", "kit", "domains", "maaos"):
        shutil.copytree(_REPO_ROOT / package, root / package,
                        ignore=shutil.ignore_patterns("__pycache__"))
    for package in ("domain", "symbolic", "nl"):          # domains.registry imports BoxPush
        shutil.copytree(_REPO_ROOT / package, root / package,
                        ignore=shutil.ignore_patterns("__pycache__"))
    (root / "tests").mkdir()
    (root / "tests" / "__init__.py").write_text("", encoding="utf-8")
    shutil.copy(_REPO_ROOT / "tests" / "test_no_backend_imports.py", root / "tests")
    return root


def _run_in(root: pathlib.Path, script: str) -> dict:
    env = dict(os.environ, PYTHONPATH=str(root), SDL_VIDEODRIVER="dummy")
    completed = subprocess.run(
        [sys.executable, "-B", "-c", script], cwd=root, env=env,
        capture_output=True, text=True, timeout=300,
    )
    if completed.returncode != 0:
        raise AssertionError(completed.stdout + completed.stderr)
    return json.loads(completed.stdout.strip().splitlines()[-1])


