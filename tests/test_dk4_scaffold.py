class TestRender(unittest.TestCase):
    def test_six_files_with_the_name_substituted_and_no_marker_left(self):
        files = render("warehouse", package_import="domains.warehouse",
                       test_module="tests.test_domain_warehouse")
        self.assertEqual(set(files), set(_PACKAGE_FILES) | {"tests/test_domain_warehouse.py"})
        for path, content in files.items():
            self.assertNotIn("__NAME__", content, path)
            self.assertNotIn("__PACKAGE_IMPORT__", content, path)
            self.assertNotIn("__TEST_MODULE__", content, path)
            self.assertIn("warehouse", content, path)
        self.assertIn("from domains.warehouse import DOMAIN", files["tests/test_domain_warehouse.py"])
        self.assertIn('name="warehouse"', files["__init__.py"])
        for template in _TEMPLATES.glob("*.py.tmpl"):
            self.assertIn("TODO(author)", template.read_text(encoding="utf-8"), template.name)

    def test_generated_python_parses_and_follows_the_module_roles(self):
        files = render("lamp", package_import="domains.lamp", test_module="tests.test_domain_lamp")
        for path, content in files.items():
            if path.endswith(".py"):
                ast.parse(content, filename=path)
        with contextlib.ExitStack() as stack:
            root = pathlib.Path(stack.enter_context(tempfile.TemporaryDirectory()))
            pkg = root / "domains" / "lamp"
            pkg.mkdir(parents=True)
            (root / "domains" / "__init__.py").write_text("", encoding="utf-8")
            for name in _PACKAGE_FILES:
                (pkg / name).write_text(files[name], encoding="utf-8")
            (root / "tests").mkdir()
            (root / "tests" / "test_no_backend_imports.py").write_text(
                "DOMAIN_ENVIRONMENT_MODULES = frozenset()\n", encoding="utf-8")
            self.assertEqual(domain_role_violations(root), [])
            self.assertEqual([f.status for f in check_layout("lamp", repo_root=root)],
                             [Status.PASS, Status.PASS])


class TestAFreshScaffoldValidatesOutOfTheBox(unittest.TestCase):
    def test_generate_import_validate_and_run_in_a_scratch_copy(self):
        with contextlib.ExitStack() as stack:
            root = _scratch_repo(stack)
            created = create_domain("fresh", repo_root=root)
            self.assertEqual(created.package_import, "domains.fresh")
            self.assertEqual(len(created.written), 6)
